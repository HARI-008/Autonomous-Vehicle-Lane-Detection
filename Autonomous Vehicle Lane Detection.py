cap = cv2.VideoCapture(video_path)

if not cap.isOpened():
    raise ValueError("Unable to open uploaded video.")

fps = cap.get(cv2.CAP_PROP_FPS)

if not fps or fps <= 0:
    fps = 25

original_width = int(
    cap.get(cv2.CAP_PROP_FRAME_WIDTH)
)

original_height = int(
    cap.get(cv2.CAP_PROP_FRAME_HEIGHT)
)

output_width = min(original_width, 1280)

output_height = int(
    original_height * output_width / original_width
)

fourcc = cv2.VideoWriter_fourcc(*"mp4v")

writer = cv2.VideoWriter(
    output_path,
    fourcc,
    fps,
    (output_width, output_height)
)

if not writer.isOpened():
    cap.release()
    raise RuntimeError("Unable to create output video.")

frame_count = 0

sample_original = None
sample_edges = None
sample_roi = None
sample_result = None

print("Processing video...")

while True:

    ret, frame = cap.read()

    if not ret:
        break

    result, edges, roi = process_frame(frame)

    result = cv2.resize(
        result,
        (output_width, output_height)
    )

    writer.write(result)

    if sample_original is None:

        sample_original = cv2.cvtColor(
            frame,
            cv2.COLOR_BGR2RGB
        )

        sample_edges = edges
        sample_roi = roi

        sample_result = cv2.cvtColor(
            result,
            cv2.COLOR_BGR2RGB
        )

    frame_count += 1

    if frame_count % 100 == 0:
        print("Frames processed:", frame_count)


cap.release()
writer.release()

print("Video processing completed.")
print("Total frames:", frame_count)


