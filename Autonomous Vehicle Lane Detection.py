# REGION OF INTEREST

def region_of_interest(image):

    height, width = image.shape[:2]

    polygon = np.array([[
        (int(width * 0.08), height),
        (int(width * 0.42), int(height * 0.58)),
        (int(width * 0.58), int(height * 0.58)),
        (int(width * 0.92), height)
    ]], dtype=np.int32)

    mask = np.zeros_like(image)

    cv2.fillPoly(mask, polygon, 255)

    return cv2.bitwise_and(image, mask)


# LANE LINE DETECTION

def average_lane_lines(image, lines):

    height, width = image.shape[:2]

    left_points = []
    right_points = []

    if lines is None:
        return None, None

    for line in lines:

        x1, y1, x2, y2 = line.reshape(4)

        if x2 == x1:
            continue

        slope = (y2 - y1) / (x2 - x1)

        if abs(slope) < 0.35 or abs(slope) > 3:
            continue

        length = np.hypot(x2 - x1, y2 - y1)

        points = [
            (x1, y1, length),
            (x2, y2, length)
        ]

        if slope < 0:
            left_points.extend(points)
        else:
            right_points.extend(points)

    def fit_line(points):

        if len(points) < 2:
            return None

        points = np.array(points, dtype=float)

        try:
            slope, intercept = np.polyfit(
                points[:, 0],
                points[:, 1],
                1,
                w=np.sqrt(points[:, 2])
            )
        except (ValueError, np.linalg.LinAlgError):
            return None

        if abs(slope) < 1e-6:
            return None

        y_bottom = height
        y_top = int(height * 0.60)

        x_bottom = int((y_bottom - intercept) / slope)
        x_top = int((y_top - intercept) / slope)

        if not (-width <= x_bottom <= 2 * width):
            return None

        if not (-width <= x_top <= 2 * width):
            return None

        return (x_bottom, y_bottom, x_top, y_top)

    left = fit_line(left_points)
    right = fit_line(right_points)

    return left, right


# DRAW LANE LINES

def draw_lane_lines(frame, left, right):

    line_image = np.zeros_like(frame)

    for line in [left, right]:

        if line is not None:

            x1, y1, x2, y2 = line

            cv2.line(
                line_image,
                (x1, y1),
                (x2, y2),
                (0, 255, 0),
                10
            )

    return cv2.addWeighted(
        frame,
        0.85,
        line_image,
        1.0,
        0
    )


# PROCESS VIDEO FRAME

def process_frame(frame):

    height, width = frame.shape[:2]

    if width > 1280:
        frame = cv2.resize(
            frame,
            (1280, int(height * 1280 / width))
        )

    # Convert to grayscale
    gray = cv2.cvtColor(
        frame,
        cv2.COLOR_BGR2GRAY
    )

    # Apply Gaussian blur
    blurred = cv2.GaussianBlur(
        gray,
        (5, 5),
        0
    )

    # Canny edge detection
    edges = cv2.Canny(
        blurred,
        50,
        150
    )

    # Apply Region of Interest
    roi = region_of_interest(edges)

    # Hough Line Transform
    lines = cv2.HoughLinesP(
        roi,
        rho=2,
        theta=np.pi / 180,
        threshold=50,
        minLineLength=40,
        maxLineGap=100
    )

    # Identify left and right lanes
    left, right = average_lane_lines(
        frame,
        lines
    )

    # Draw detected lanes
    result = draw_lane_lines(
        frame,
        left,
        right
    )

    cv2.putText(
        result,
        "Autonomous Vehicle Lane Detection",
        (25, 40),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.8,
        (255, 255, 255),
        2
    )

    return result, edges, roi


